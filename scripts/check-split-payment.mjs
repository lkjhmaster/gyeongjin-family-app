import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
import assert from 'node:assert/strict';
const html=readFileSync('index.html','utf8');
const worker=readFileSync('src/worker.js','utf8').replace(/^import .*;\r?\n/gm,'');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(Boolean);
assert(scripts.length>0,'missing inline JavaScript');
for(const source of scripts)new Script(source,{filename:'index.html:inline'});
new Script(worker.replace(/export\s+default\s*\{/,'const __worker = {'),{filename:'src/worker.js'});
for(const name of ['splitPaymentForm','splitPaymentSubmit','reviewSplitPayment','cancelSplitPayment'])assert(html.includes('function '+name+'('),'missing '+name);
assert(worker.includes('/api/allowance/split/review'),'missing atomic split endpoint');
assert(worker.includes('AND value_json=?'),'missing CAS update');
assert(worker.includes('tx.status!=="pending"'),'missing pending status guard');
assert(worker.includes('tx.status!=="approved"'),'missing cancellation status guard');
assert(html.includes("api('/api/allowance/split/review'"),'client server-review integration missing');
assert(html.includes('split_debt_origin'),'minus origin selector missing');
assert(worker.includes('tx.debtOrigin'),'minus origin validation missing');
assert(worker.includes(String.raw`/^\d{4}-\d{2}-\d{2}$/`),'split request date validation broken');
assert(worker.includes('duplicate:true'),'request retry idempotency missing');
assert(worker.includes('/api/allowance/split/request'),'request endpoint missing');
assert(worker.includes('new Set(parts.map(x=>x.wallet)).size!==parts.length'),'cancellation wallet uniqueness check missing');
assert(worker.includes('(x.status||"approved")==="approved"'),'legacy approved transactions excluded');
assert(html.includes('x.splitPaymentId?'),'individual split part edit/delete protection missing');
assert(worker.includes('통합결제 생성은 전용 API'),'generic ledger injection protection missing');
assert(worker.includes('통합결제 변경은 전용 API'),'generic ledger mutation protection missing');
console.log('PASS: JavaScript syntax and split payment safety contract');

