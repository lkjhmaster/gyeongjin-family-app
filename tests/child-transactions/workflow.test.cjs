'use strict';
const assert=require('node:assert/strict');
const {transition,canBorrow,canSettleGoods,approvalReady,idempotencyKey}=require('../../src/child-transactions/workflow.cjs');
assert.equal(transition('requested','consented'),'consented');
assert.equal(transition('consented','approved'),'approved');
assert.equal(transition('approved','held'),'held');
assert.equal(transition('held','delivery_pending'),'delivery_pending');
assert.throws(()=>transition('requested','settled'),/invalid/);
assert.throws(()=>transition('settled','held'),/invalid/);
assert.equal(canBorrow([{borrowerId:'A',outstanding:100,status:'active'}],'A'),false);
assert.equal(canBorrow([{borrowerId:'A',outstanding:100,status:'active'}],'B'),true);
assert.equal(canBorrow([{borrowerId:'A',outstanding:0,status:'settled'}],'A'),true);
assert.equal(canSettleGoods({kind:'goods',status:'delivery_pending',buyerConfirmed:true,sellerConfirmed:true,parentApproved:true,holdActive:true}),true);
assert.equal(canSettleGoods({kind:'goods',status:'delivery_pending',buyerConfirmed:true,sellerConfirmed:false,parentApproved:true,holdActive:true}),false);
assert.equal(approvalReady({requesterConsented:true,counterpartyConsented:true,parentApproved:false,status:'consented'}),true);
assert.equal(approvalReady({requesterConsented:true,counterpartyConsented:false,parentApproved:false,status:'consented'}),false);
assert.equal(idempotencyKey('t1',2,'approve'),'t1:2:approve');
assert.throws(()=>idempotencyKey('t1',-1,'approve'),/invalid/);
console.log('15 workflow assertions passed');
